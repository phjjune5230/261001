--  대화 압축 상태 (compaction)
--
--  실행 대상: Supabase 대시보드 → SQL Editor → New query → 이 붙여넣기 → Run
--
--  ★ schema.sql → single-user.sql 순으로 이미 실행한 뒤에 이걸 실행합니다. ★
--
--  ─────────────────────────────────────────────────────────────────────────
--  무엇을 하나
--  conversations에 jsonb 열 하나를 추가합니다. 앞에서부터 몇 개의 메시지를
--  요약이 덮었는지, 그 요약이 뭔지를 담습니다.
--
--  ─────────────────────────────────────────────────────────────────────────
--  왜 messages.meta가 아니라 여기인가
--  ─────────────────────────────────────────────────────────────────────────
--  messages.meta는 영어 학습의 예문·연습 단계를 원형으로 보존하는 자리입니다 (D-016).
--  압축 상태를 거기 섞으면 원본과 파생물이 같은 열에 섞여 구분할 수 없습니다.
--  압축 상태는 메시지의 속성이 아니라 대화의 속성입니다 — 대화를 열 때마다
--  어디까지 덮였는지 다시 계산해야 하므로 자리에 맞습니다.
--
--  ─────────────────────────────────────────────────────────────────────────
--  실행 안 했어도 앱은 돌아갑니다
--  lib/compaction.ts의 읽기·쓰기가 둘 다 실패를 삼키고 null/false를 돌려줍니다.
--  "압축이 꺼진 상태"는 정상 상태로 취급해야 하기 때문입니다 — 500을 내면서
--  "SQL 하나 실행하세요"라고 하는 것보다 조용히 예전처럼 버리는 편이 낫습니다.
--  다만 그랬다면 대화가 100턴을 넘어도 "아까 그 얘기"가 풀리지 않습니다.
--
--  여러 번 실행해도 안전합니다 (if not exists).
-- ============================================================================


alter table public.conversations
  add column if not exists compaction jsonb;

